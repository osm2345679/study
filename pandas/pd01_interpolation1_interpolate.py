"""

결측치 처리
1. 삭제 - 행 또는 열 전체 삭제
2. 임의의 값
    - 0 : fillna
    - 평균 : mean (이상치에 크게 영향 받음)
    - 중위 : median
    - 직전 값 : ffill
    - 직후 값 : bfill
    - 특정 값 : 77 (조건 보고 넣기)
    - 최빈 값
    - 기타 등등
3. interpolate - 보간(알려진 데이터 점 집합의 범위 내에 새 데이터 점을 추가하는 기법)
4. 모델 : predict(전혀 다른 모델 사용)
5. 부스팅(트리) 계열 모델 사용 : 일반적으로 결측치, 이상치에 대한 영향을 덜 받음
6. 스케일링(scaling) : robust 등 (이상치 영향 줄여줌)

"""

import pandas as pd
import numpy as np

data = [
    '11/11/2026', '12/11/2026', '13/11/2026',
    '14/11/2026', '15/11/2026', '16/11/2026',
    '17/11/2026', '18/11/2026', '19/11/2026'
]

dates = pd.to_datetime(data, dayfirst=True)
print(dates)
# DatetimeIndex(['2026-11-11', '2026-11-12', '2026-11-13', '2026-11-14',
#                '2026-11-15', '2026-11-16', '2026-11-17', '2026-11-18',
#                '2026-11-19'],
#               dtype='datetime64[us]', freq=None)

print("====================================================")
ts = pd.Series([np.nan, 2, np.nan, np.nan, 8, 10, np.nan, 1, np.nan], index=dates)
print(ts)
# ====================================================
# 2026-11-11     0.0
# 2026-11-12     2.0
# 2026-11-13     NaN
# 2026-11-14     NaN
# 2026-11-15     8.0
# 2026-11-16    10.0
# 2026-11-17     NaN
# 2026-11-18     1.0
# 2026-11-19    16.0
# dtype: float64

print("====================================================")
ts = ts.interpolate()
print(ts)
# ====================================================
# 2026-11-11     NaN
# 2026-11-12     2.0
# 2026-11-13     4.0
# 2026-11-14     6.0
# 2026-11-15     8.0
# 2026-11-16    10.0
# 2026-11-17     5.5
# 2026-11-18     1.0
# 2026-11-19     1.0
# dtype: float64

# 중간 값은 linear로 채워짐
# 마지막 값은 ffill로 채워짐
# 첫번째 값은 처리 안 함.